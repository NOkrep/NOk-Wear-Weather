import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const evidenceRoot = resolve(process.env.NOK_STUDIO_EVIDENCE_ROOT || resolve(root, '../NOk_Sites&Extensions/NOk-Weathrobe-Release/evidence/ww21'));
const folder = resolve(evidenceRoot, 'ww21-studio');
const manifestPath = resolve(folder, 'manifest.json');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const types = ['short-sleeve-tee', 'shirt', 'sweatshirt', 'puffer', 'jeans', 'sneakers'];
const expected = types.flatMap(type => Array.from({ length: 5 }, (_, i) => type + ':' + i));
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
if (manifest.assets.length !== 30 || new Set(manifest.assets.map(a => a.designId)).size !== 30 || expected.some(id => !manifest.assets.some(a => a.designId === id))) throw new Error('Exactly the thirty approved studio designs are required');

const prepared = [];
for (const id of expected) {
  const asset = manifest.assets.find(a => a.designId === id);
  if (asset.file !== asset.type + '-' + asset.variant + '.png' || asset.designId !== asset.type + ':' + asset.variant || !/^[a-z0-9-]+\.png$/.test(asset.file)) throw new Error('Invalid source identity: ' + id);
  const source = readFileSync(resolve(folder, asset.file));
  const digest = hash(source);
  if (asset.sha256 && asset.sha256 !== digest) throw new Error('Source changed unexpectedly: ' + asset.file);
  const { data, info } = await sharp(source).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let left = info.width, top = info.height, right = 0, bottom = 0, transparent = 0, edge = 0;
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
    const alpha = data[(y * info.width + x) * 4 + 3];
    if (!alpha) transparent++;
    if (alpha > 200) {
      left = Math.min(left, x); top = Math.min(top, y); right = Math.max(right, x); bottom = Math.max(bottom, y);
      if (!x || !y || x === info.width - 1 || y === info.height - 1) edge++;
    }
  }
  if (edge || transparent < info.width * info.height * .15 || right <= left || bottom <= top) throw new Error('Transparency or uncropped silhouette check failed: ' + id);
  // Retain a margin around measured alpha; never approximate organic edges with a geometric mask.
  const crop = { left: Math.max(0, left - 12), top: Math.max(0, top - 12), width: 0, height: 0 };
  crop.width = Math.min(info.width, right + 13) - crop.left;
  crop.height = Math.min(info.height, bottom + 13) - crop.top;
  const output = await sharp(source).extract(crop).resize(640, 640, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } }).webp({ quality: 84, alphaQuality: 100, effort: 6 }).toBuffer();
  const outputHash = hash(output), filename = asset.type + '-' + asset.variant + '-' + outputHash.slice(0, 12) + '.webp';
  const production = { file: filename, src: '/garments/studio/' + filename, width: 640, height: 640, bytes: output.length, sha256: outputHash };
  prepared.push({ output, asset: { ...asset, width: info.width, height: info.height, bytes: source.length, sha256: digest,
    alpha: { fullyTransparentFraction: transparent / (info.width * info.height), opaqueBounds: [left, top, right, bottom] }, production } });
}
const outputFolder = resolve(root, 'public/garments/studio');
mkdirSync(outputFolder, { recursive: true });
for (const { output, asset } of prepared) writeFileSync(resolve(outputFolder, asset.production.file), output);
manifest.schemaVersion = 2;
manifest.status = manifest.finalReview?.accepted === true ? 'thirty-variants-and-local-integration-accepted' : 'thirty-variants-review-pending';
manifest.scope = manifest.finalReview?.accepted === true
  ? 'Thirty model variants across the same six types and local integration accepted by the user. Six accepted base sources preserved; no live deployment.'
  : 'Thirty model variants across the same six types. Six accepted base sources preserved; remaining variants and local integration await visual acceptance.';
manifest.assets = prepared.map(p => p.asset);
manifest.optimization = { tool: 'Existing installed sharp', format: 'WebP', size: 640, quality: 84, alphaQuality: 100, sourcePNGsPreserved: true };
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
const map = Object.fromEntries(prepared.map(({ asset: a }) => [a.designId, { designId: a.designId, src: a.production.src, width: a.production.width, height: a.production.height, sha256: a.production.sha256 }]));
writeFileSync(resolve(root, 'lib/garment-studio-assets.ts'), '/** Generated by scripts/preview/prepare-garment-studio-assets.mjs; synthetic model references, never product facts. */\nexport interface StudioAsset { designId: string; src: string; width: number; height: number; sha256: string }\nexport const STUDIO_ASSETS: Readonly<Record<string, StudioAsset>> = Object.freeze(' + JSON.stringify(map, null, 2) + ');\n');
console.log(JSON.stringify({ designs: prepared.length, sourceBytes: prepared.reduce((sum, p) => sum + p.asset.bytes, 0), webpBytes: prepared.reduce((sum, p) => sum + p.output.length, 0) }));
